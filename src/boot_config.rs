//! Reads and writes the Raspberry Pi boot config (`/boot/firmware/config.txt`).

use std::io;
use std::path::PathBuf;

use crate::hats::{self, HatProfile};

pub struct BootConfigService {
    path: PathBuf,
}

impl BootConfigService {
    pub fn from_env() -> Self {
        let path = std::env::var("CONFIG_PATH").unwrap_or_else(|_| "/boot/firmware/config.txt".into());
        Self { path: path.into() }
    }

    /// Guesses the configured HAT from `config.txt`. `None` if the file cannot be read.
    pub async fn get_active_config(&self) -> Option<&'static HatProfile> {
        match tokio::fs::read_to_string(&self.path).await {
            Ok(content) => Some(detect_active_hat(&content)),
            Err(error) => {
                tracing::error!("Failed to read {}: {error}", self.path.display());
                None
            }
        }
    }

    /// Whether `force_eeprom_read=0` is set.
    pub async fn is_eeprom_read_disabled(&self) -> bool {
        tokio::fs::read_to_string(&self.path)
            .await
            .map(|content| content.contains("force_eeprom_read=0"))
            .unwrap_or(false)
    }

    /// Writes the overlay block for `hat_id` into `config.txt`.
    pub async fn set_hat(&self, hat_id: &str) -> io::Result<()> {
        if hats::find(hat_id).is_none() {
            return Err(io::Error::new(io::ErrorKind::InvalidInput, "Invalid HAT ID"));
        }
        let content = tokio::fs::read_to_string(&self.path).await?;
        tokio::fs::write(&self.path, apply_hat(&content, hat_id)).await
    }
}

/// Checks, in order: our explicit `# BEATNIK_ACTIVE_HAT=<id>` marker, an active `dtoverlay`
/// line of a known HAT, else the `none` profile.
pub fn detect_active_hat(content: &str) -> &'static HatProfile {
    let marker = content
        .split('\n')
        .find_map(|line| line.strip_prefix("# BEATNIK_ACTIVE_HAT=").filter(|id| !id.is_empty()));
    if let Some(hat) = marker.and_then(|id| hats::find(id.trim())) {
        return hat;
    }

    for hat in hats::SUPPORTED_HATS {
        if hat.id == "none" || hat.id == "usb-dac" {
            continue;
        }
        // Overlay at the start of a line (not commented out), followed by end, whitespace or ','
        let active = content.split('\n').any(|line| {
            line.trim_start()
                .strip_prefix(hat.overlay)
                .is_some_and(|rest| rest.chars().next().is_none_or(|c| c.is_whitespace() || c == ','))
        });
        if active {
            return hat;
        }
    }

    hats::find("none").expect("'none' profile exists")
}

/// Returns the new `config.txt` content with the Beatnik block for `hat_id`.
pub fn apply_hat(content: &str, hat_id: &str) -> String {
    let hat = hats::find(hat_id).expect("hat_id is validated by the caller");
    let mut lines: Vec<String> = Vec::new();

    // 1. Clean up the old configuration
    for line in content.split('\n') {
        let mut keep = true;
        let mut current = line.to_string();

        // Add/remove `noaudio` on the KMS overlay depending on the HAT
        if current.trim().starts_with("dtoverlay=vc4-kms-v3d") {
            let (config, comment) = match current.split_once('#') {
                Some((config, rest)) => (config.to_string(), format!(" #{rest}")),
                None => (current.clone(), String::new()),
            };
            let mut parts = config.split(',').map(str::trim);
            let base = parts.next().unwrap_or_default();
            let mut params: Vec<&str> = parts.filter(|p| *p != "noaudio" && !p.is_empty()).collect();
            // Disable HDMI audio unless HDMI is the output, to avoid conflicts
            if hat_id != "rpi-hdmi0" {
                params.push("noaudio");
            }
            current = std::iter::once(base).chain(params).collect::<Vec<_>>().join(",") + &comment;
        }

        // Remove existing HiFiBerry and IQaudIO overlays
        let trimmed = current.trim();
        if trimmed.starts_with("dtoverlay=hifiberry") || trimmed.starts_with("dtoverlay=iqaudio") {
            keep = false;
        }

        // Comment out onboard audio settings instead of deleting them
        if trimmed.starts_with("dtparam=audio=") {
            lines.push(format!("# {current}"));
            keep = false;
        }

        // Remove our own markers from earlier runs
        if current.contains("BEATNIK AUDIO CONFIGURATION") || current.contains("BEATNIK_ACTIVE_HAT=") {
            keep = false;
        }

        if keep {
            lines.push(current);
        }
    }

    // 2. Append the new block
    lines.push(String::new());
    lines.push("############################".into());
    lines.push("# BEATNIK AUDIO CONFIGURATION".into());
    lines.push("# Automatically generated by beatnik-hardware-service".into());
    lines.push(format!("# BEATNIK_ACTIVE_HAT={hat_id}"));
    if hat_id != "none" && hat_id != "usb-dac" {
        lines.push(hat.overlay.into());
        lines.push("dtparam=audio=off".into());
    } else {
        lines.push("dtparam=audio=on".into());
    }
    lines.push("############################".into());
    lines.push(String::new());

    collapse_blank_lines(&lines.join("\n"))
}

/// Replaces runs of 3+ newlines with exactly two.
fn collapse_blank_lines(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    let mut newlines = 0;
    for c in text.chars() {
        if c == '\n' {
            newlines += 1;
            if newlines <= 2 {
                out.push(c);
            }
        } else {
            newlines = 0;
            out.push(c);
        }
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn detects_marker_first() {
        let content = "dtoverlay=hifiberry-dac\n# BEATNIK_ACTIVE_HAT=hifiberry-amp\n";
        assert_eq!(detect_active_hat(content).id, "hifiberry-amp");
    }

    #[test]
    fn detects_overlay_without_marker() {
        assert_eq!(detect_active_hat("  dtoverlay=hifiberry-dacplus-pro,foo\n").id, "hifiberry-dacplus-pro");
        // Commented out or only a prefix of a longer overlay name
        assert_eq!(detect_active_hat("#dtoverlay=hifiberry-dac\n").id, "none");
        assert_eq!(detect_active_hat("dtoverlay=hifiberry-dacplus-xr\n").id, "hifiberry-dacplus-xr");
    }

    #[test]
    fn unknown_marker_falls_back_to_overlay() {
        assert_eq!(
            detect_active_hat("# BEATNIK_ACTIVE_HAT=nope\ndtoverlay=hifiberry-amp\n").id,
            "hifiberry-amp"
        );
    }

    #[test]
    fn apply_hat_rewrites_config() {
        let input = "\
[all]
dtoverlay=vc4-kms-v3d # kms
dtparam=audio=on
dtoverlay=hifiberry-dac



############################
# BEATNIK AUDIO CONFIGURATION
# BEATNIK_ACTIVE_HAT=hifiberry-dac
";
        let expected = "\
[all]
dtoverlay=vc4-kms-v3d,noaudio # kms
# dtparam=audio=on

############################

############################
# BEATNIK AUDIO CONFIGURATION
# Automatically generated by beatnik-hardware-service
# BEATNIK_ACTIVE_HAT=hifiberry-amp
dtoverlay=hifiberry-amp
dtparam=audio=off
############################
";
        assert_eq!(apply_hat(input, "hifiberry-amp"), expected);
    }

    #[test]
    fn hdmi_keeps_hdmi_audio() {
        let out = apply_hat("dtoverlay=vc4-kms-v3d,noaudio\n", "rpi-hdmi0");
        assert!(out.starts_with("dtoverlay=vc4-kms-v3d\n"));
        assert!(out.contains("# Beatnik HDMI0\ndtparam=audio=off"));
    }

    #[test]
    fn no_hat_enables_onboard_audio() {
        let out = apply_hat("", "none");
        assert!(out.contains("# BEATNIK_ACTIVE_HAT=none\ndtparam=audio=on\n"));
    }
}
